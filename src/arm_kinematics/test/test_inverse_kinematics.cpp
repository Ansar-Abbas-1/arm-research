#include <gtest/gtest.h>

#include <cmath>
#include <memory>
#include <random>

#include <ros/package.h>
#include <urdf/model.h>

#include "arm_kinematics/forward_kinematics.h"
#include "arm_kinematics/inverse_kinematics.h"

namespace {

urdf::Model LoadArmModel() {
  urdf::Model model;
  std::string arm_interface_path = ros::package::getPath("arm_interface");
  EXPECT_FALSE(arm_interface_path.empty()) << "arm_interface package not found";
  EXPECT_TRUE(model.initFile(arm_interface_path + "/urdf/arm.urdf"));
  return model;
}

}  // namespace

class InverseKinematicsTest : public ::testing::Test {
 protected:
  void SetUp() override {
    model_ = LoadArmModel();
    fk_ = std::make_unique<arm_kinematics::ForwardKinematicsSolver>(model_, "base_link",
                                                                     "link_5");
    // Fixed rng_seed: restarts are otherwise seeded from std::random_device,
    // which would make this test's pass/fail non-reproducible run to run.
    arm_kinematics::IkOptions options;
    options.rng_seed = 42;
    ik_ = std::make_unique<arm_kinematics::InverseKinematicsSolver>(*fk_, options);
  }

  urdf::Model model_;
  std::unique_ptr<arm_kinematics::ForwardKinematicsSolver> fk_;
  std::unique_ptr<arm_kinematics::InverseKinematicsSolver> ik_;
};

TEST_F(InverseKinematicsTest, RoundTripFromRandomReachableTargets) {
  // Targets generated BY running FK on random valid joint configs, so
  // reachability is known by construction -- then IK is solved from a
  // *different* seed (the zero config) to make sure it's actually solving,
  // not just returning the seed unchanged.
  std::mt19937 rng(7);
  const auto& limits = fk_->GetActuatedJointLimits();
  std::vector<std::uniform_real_distribution<double>> dists;
  for (const auto& lim : limits) {
    dists.emplace_back(lim.first, lim.second);
  }

  const std::vector<double> zero_seed(limits.size(), 0.0);

  int num_converged = 0;
  const int kTrials = 20;
  for (int trial = 0; trial < kTrials; ++trial) {
    std::vector<double> q_true(limits.size());
    for (size_t i = 0; i < limits.size(); ++i) {
      q_true[i] = dists[i](rng);
    }
    Eigen::Isometry3d target = fk_->ComputePose(q_true);

    auto result = ik_->Solve(target, zero_seed);
    if (result.converged) {
      ++num_converged;
      Eigen::Isometry3d achieved = fk_->ComputePose(result.joint_positions);
      EXPECT_LT((achieved.translation() - target.translation()).norm(), 1e-3)
          << "trial " << trial;
    }
  }
  // A fixed seed alone (even with well-tuned adaptive damping) converges
  // only ~35% of the time on this redundant chain -- confirmed empirically,
  // see InverseKinematicsSolver's class comment. Restarts are what make
  // this reliably ~100%; if this regresses, look at max_restarts/the
  // restart seeding, not damping.
  EXPECT_EQ(num_converged, kTrials);
}

TEST_F(InverseKinematicsTest, UnreachableTargetReportsNotConverged) {
  const auto& limits = fk_->GetActuatedJointLimits();
  std::vector<double> zero_seed(limits.size(), 0.0);

  Eigen::Isometry3d target = Eigen::Isometry3d::Identity();
  target.translation() = Eigen::Vector3d(10.0, 10.0, 10.0);  // far outside max reach (~1.2 m)

  auto result = ik_->Solve(target, zero_seed);
  EXPECT_FALSE(result.converged);
  // Every restart should have been exhausted too (nothing here is ever
  // reachable, so no restart can converge either).
  EXPECT_EQ(result.restarts_used, arm_kinematics::IkOptions().max_restarts);
  // Even non-converged, the result must be physically valid: joint limits
  // respected and no NaN/Inf poisoning the residual.
  for (size_t i = 0; i < limits.size(); ++i) {
    EXPECT_GE(result.joint_positions[i], limits[i].first);
    EXPECT_LE(result.joint_positions[i], limits[i].second);
  }
  EXPECT_TRUE(result.residual.allFinite());
}

TEST_F(InverseKinematicsTest, NumericallyStableNearJointLimitBoundary) {
  // Not a proven exact kinematic singularity -- just a boundary/extreme
  // configuration (all joints at a limit) used as a stress case for the
  // damping term's numerical robustness. Success criterion here is "no
  // NaN/Inf and limits respected", not convergence.
  const auto& limits = fk_->GetActuatedJointLimits();
  std::vector<double> seed(limits.size());
  for (size_t i = 0; i < limits.size(); ++i) {
    seed[i] = limits[i].first;
  }

  Eigen::Isometry3d target = Eigen::Isometry3d::Identity();
  target.translation() = Eigen::Vector3d(0.5, 0.2, 0.3);
  target.linear() = Eigen::AngleAxisd(1.0, Eigen::Vector3d::UnitY()).toRotationMatrix();

  auto result = ik_->Solve(target, seed);
  ASSERT_TRUE(result.residual.allFinite());
  for (size_t i = 0; i < limits.size(); ++i) {
    EXPECT_GE(result.joint_positions[i], limits[i].first);
    EXPECT_LE(result.joint_positions[i], limits[i].second);
    EXPECT_TRUE(std::isfinite(result.joint_positions[i]));
  }
}

TEST_F(InverseKinematicsTest, WrongSeedSizeThrows) {
  Eigen::Isometry3d target = Eigen::Isometry3d::Identity();
  EXPECT_THROW(ik_->Solve(target, {0.0, 0.0}), std::invalid_argument);
}

int main(int argc, char** argv) {
  testing::InitGoogleTest(&argc, argv);
  return RUN_ALL_TESTS();
}
