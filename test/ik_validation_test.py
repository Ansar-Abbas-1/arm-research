#!/usr/bin/env python3
"""Integration test: /solve_ik against the real simulator, end to end.

Targets are generated by driving the sim to a known joint configuration
and reading its own TF (base_link -> end_effector) as ground truth -- avoids
hardcoding any numeric reference pose, and guarantees reachability by
construction. IK is then solved from an explicit, different seed, and the
returned joint_positions are driven back through the sim to confirm they
reproduce the same TF pose: an IK-then-FK round trip closed through the
actual simulator, not just the solver in isolation.
"""
import math
import random
import unittest

import rospy
import rostest
import tf2_ros
from arm_kinematics.srv import SolveIk, SolveIkRequest
from geometry_msgs.msg import Pose
from sensor_msgs.msg import JointState

PKG = "arm_kinematics"

# From urdf/arm.urdf, joints 1-5 (same as fk_validation_test.py).
JOINT_LIMITS = [
    (-2.745, 2.745),
    (0.0, 3.14),
    (-2.220, 0.0),
    (0.0, 4.505),
    (-3.62, 0.0),
]

POS_TOL = 1e-3   # meters -- looser than fk_validation_test.py's, since this
ROT_TOL = 1e-2   # radians  round-trips through a numerical IK solve, not exact FK


def quat_angle_diff(q1, q2):
    dot = q1.x * q2.x + q1.y * q2.y + q1.z * q2.z + q1.w * q2.w
    dot = max(-1.0, min(1.0, abs(dot)))
    return 2.0 * math.acos(dot)


class InverseKinematicsValidationTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        rospy.init_node("ik_validation_test")
        cls.pub = rospy.Publisher("/joint_states_out", JointState, queue_size=10)
        cls.tf_buffer = tf2_ros.Buffer()
        cls.tf_listener = tf2_ros.TransformListener(cls.tf_buffer)

        rospy.wait_for_service("/solve_ik", timeout=30.0)
        cls.solve_ik = rospy.ServiceProxy("/solve_ik", SolveIk)

        deadline = rospy.Time.now() + rospy.Duration(10.0)
        while rospy.Time.now() < deadline and cls.pub.get_num_connections() == 0:
            rospy.sleep(0.1)
        rospy.sleep(1.0)

    def _drive(self, q):
        msg = JointState()
        msg.name = ["joint_1", "joint_2", "joint_3", "joint_4", "joint_5", "joint_6"]
        msg.position = list(q) + [0.0]
        end = rospy.Time.now() + rospy.Duration(1.0)
        while rospy.Time.now() < end:
            msg.header.stamp = rospy.Time.now()
            self.pub.publish(msg)
            rospy.sleep(0.05)

    def _current_tf_pose(self):
        tf = self.tf_buffer.lookup_transform(
            "base_link", "end_effector", rospy.Time(0), rospy.Duration(2.0)
        )
        pose = Pose()
        pose.position.x = tf.transform.translation.x
        pose.position.y = tf.transform.translation.y
        pose.position.z = tf.transform.translation.z
        pose.orientation = tf.transform.rotation
        return pose

    def _pose_error(self, a, b):
        pos_err = math.sqrt(
            (a.position.x - b.position.x) ** 2
            + (a.position.y - b.position.y) ** 2
            + (a.position.z - b.position.z) ** 2
        )
        rot_err = quat_angle_diff(a.orientation, b.orientation)
        return pos_err, rot_err

    def _round_trip(self, q_target, q_seed, label):
        self._drive(q_target)
        target_pose = self._current_tf_pose()

        req = SolveIkRequest()
        req.target_pose = target_pose
        req.seed_joint_positions = list(q_seed)
        res = self.solve_ik(req)

        # This chain is redundant (see docs/inverse_kinematics.md) and IK
        # uses randomized restarts on non-convergence, so it's inherently
        # probabilistic: an occasional unlucky draw not converging within
        # one call's restart budget is expected, not a bug. A real caller
        # would retry too -- one retry here turns "fails on one unlucky
        # draw" into the much rarer "fails twice in a row".
        if not res.converged:
            res = self.solve_ik(req)

        self.assertTrue(res.converged, f"[{label}] IK did not converge, residual={res.residual}")

        self._drive(res.joint_positions)
        achieved_pose = self._current_tf_pose()

        pos_err, rot_err = self._pose_error(achieved_pose, target_pose)
        self.assertLess(pos_err, POS_TOL, f"[{label}] position error {pos_err:.6f} m")
        self.assertLess(rot_err, ROT_TOL, f"[{label}] orientation error {rot_err:.6f} rad")

    def test_zero_target_from_nonzero_seed(self):
        self._round_trip([0.0] * 5, [0.3, 0.5, -0.3, 0.5, -0.5], "zero_target")

    def test_random_targets_from_zero_seed(self):
        rng = random.Random(11)
        for trial in range(5):
            q_target = [rng.uniform(lo, hi) for lo, hi in JOINT_LIMITS]
            self._round_trip(q_target, [0.0] * 5, f"random_{trial}")


if __name__ == "__main__":
    rostest.rosrun(PKG, "ik_validation_test", InverseKinematicsValidationTest)
